/// Brings an existing instance up to a newer version of a pack (a share update): its
/// content, configs and versions become the pack's; worlds, screenshots and logs stay.
pub async fn apply_update(
    client: &reqwest::Client,
    paths: &Paths,
    target_id: &str,
    file: &Path,
    progress: &(dyn Fn(&str, usize, usize) + Send + Sync),
) -> Result<Instance> {
    let mut target = instances::get(paths, target_id)?;
    // install next to it first, so a failed download leaves the instance as it was
    let fresh = import(client, paths, file, progress).await?;
    let result = (|| -> Result<Instance> {
        progress("Updating the instance", 0, 0);
        let from = paths.game_dir(&fresh.id);
        let to = paths.game_dir(target_id);
        std::fs::create_dir_all(&to)?;
        let in_pack: HashSet<String> = std::fs::read_dir(&from)?.flatten().map(|e| e.file_name().to_string_lossy().into_owned()).collect();
        for e in std::fs::read_dir(&from)?.flatten() {
            let name = e.file_name();
            let name_s = name.to_string_lossy();
            if ["saves", "logs", "screenshots", "crash-reports"].contains(&name_s.as_ref()) {
                continue;
            }
            let dest = to.join(&name);
            if dest.is_dir() {
                std::fs::remove_dir_all(&dest)?;
            } else if dest.exists() {
                std::fs::remove_file(&dest)?;
            }
            std::fs::rename(e.path(), &dest)?;
        }
        // content folders the pack no longer has go too
        for folder in ["mods", "resourcepacks", "shaderpacks"] {
            if !in_pack.contains(folder) {
                let _ = std::fs::remove_dir_all(to.join(folder));
            }
        }
        target.game_version = fresh.game_version.clone();
        target.loader = fresh.loader;
        target.loader_version = fresh.loader_version.clone();
        target.mods = fresh.mods.clone();
        instances::save(paths, &target)?;
        Ok(target.clone())
    })();
    let _ = instances::delete(paths, &fresh.id);
    result
}

pub fn read_manifest(zip: &mut zip::ZipArchive<std::fs::File>) -> Result<Manifest> {
    let mut entry = zip.by_name(MANIFEST).map_err(|_| anyhow!("Not a Tessera pack (.tapack)"))?;
    let mut buf = Vec::new();
    entry.read_to_end(&mut buf)?;
    let manifest: Manifest = serde_json::from_slice(&buf).context("reading tessera.pack.json")?;
    if manifest.format > FORMAT {
        bail!("This pack needs a newer Tessera Launcher");
    }
    Ok(manifest)
}

pub async fn import(
    client: &reqwest::Client,
    paths: &Paths,
    file: &Path,
    progress: &(dyn Fn(&str, usize, usize) + Send + Sync),
) -> Result<Instance> {
    progress("Reading pack", 0, 0);
    let mut zip = zip::ZipArchive::new(std::fs::File::open(file).context("opening the pack")?).context("not a pack file")?;
    let m = read_manifest(&mut zip)?;
    if m.loader.kind != Loader::Vanilla && m.loader.version.is_none() {
        bail!("The pack doesn't say which {:?} version it needs", m.loader.kind);
    }

    let icon = match &m.icon {
        Some(Icon::File) if zip.by_name("icon.png").is_err() => None,
        other => other.clone(),
    };
    let mut inst = instances::create(paths, &m.name, &m.minecraft, m.loader.kind, m.loader.version.clone(), icon)?;
    inst.memory_mb = m.memory_mb;
    let game = paths.game_dir(&inst.id);

    let result: Result<()> = async {
        for i in 0..zip.len() {
            let mut entry = zip.by_index(i)?;
            let name = entry.name().to_string();
            let target = if let Some(rel) = name.strip_prefix("overrides/") {
                if rel.is_empty() || entry.is_dir() {
                    continue;
                }
                game.join(safe_relative(rel)?)
            } else if name == "icon.png" {
                paths.instance(&inst.id).join("icon.png")
            } else {
                continue;
            };
            ensure_parent(&target)?;
            let mut out = std::fs::File::create(&target)?;
            std::io::copy(&mut entry, &mut out)?;
        }

        let mut downloads = Vec::new();
        for c in &m.content {
            let rel = safe_relative(&c.path)?;
            let path = if c.enabled { game.join(&rel) } else { game.join(format!("{}.disabled", c.path)) };
            downloads.push(Download { url: c.url.clone(), path, sha1: Some(c.sha1.clone()), size: Some(c.size), executable: false });
            if let Some(Source::Modrinth { project_id, version_id }) = &c.source {
                inst.mods.push(InstalledMod {
                    kind: c.kind.clone(),
                    world: None,
                    project_id: project_id.clone(),
                    version_id: version_id.clone(),
                    title: c.title.clone(),
                    version: c.version.clone().unwrap_or_default(),
                    filename: rel.file_name().map(|f| f.to_string_lossy().into_owned()).unwrap_or_default(),
                    icon_url: c.icon_url.clone(),
                });
            }
        }
        download_all(client, downloads, |d, t| progress("Downloading content", d, t)).await
    }
    .await;
    if let Err(e) = result {
        let _ = instances::delete(paths, &inst.id);
        return Err(e);
    }
    inst.pack = Some(PackSource { project_id: None, version_id: None, name: m.name.clone(), version: Some(m.version.clone()) });
    instances::save(paths, &inst)?;
    Ok(inst)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn content_kinds() {
        assert_eq!(content_kind(Path::new("mods/sodium.jar")), Some("mod"));
        assert_eq!(content_kind(Path::new("mods/sub/x.jar")), None);
        assert_eq!(content_kind(Path::new("shaderpacks/bsl.zip")), Some("shader"));
        assert_eq!(content_kind(Path::new("config/x.toml")), None);
    }

    /// Export an instance with an unknown mod and a config, import it again: same files.
    #[tokio::test]
    async fn round_trip_embeds_unknown_files() {
        let root = std::env::temp_dir().join(format!("tessera-tapack-{}", std::process::id()));
        let paths = Paths::new(root.clone());
        let client = crate::core::http_client();
        let inst = instances::create(&paths, "Pack Test", "1.21.1", Loader::Fabric, Some("0.16.9".into()), None).unwrap();
        let game = paths.game_dir(&inst.id);
        std::fs::create_dir_all(game.join("mods")).unwrap();
        std::fs::create_dir_all(game.join("config")).unwrap();
        std::fs::create_dir_all(game.join("logs")).unwrap();
        std::fs::write(game.join("mods/my-own-mod.jar.disabled"), b"not on modrinth").unwrap();
        std::fs::write(game.join("config/settings.toml"), b"a = 1").unwrap();
        std::fs::write(game.join("logs/latest.log"), b"secret").unwrap();

        let file = root.join("out.tapack");
        let opts = ExportOptions { name: "My Pack".into(), version: "2.0".into(), author: "lephor".into(), summary: String::new(), include: vec!["mods".into(), "config".into(), "logs".into()], format: PackFormat::Tapack };
        let report = export(&client, &paths, &inst.id, &file, opts, &|_, _, _| {}).await.unwrap();
        assert_eq!((report.linked, report.embedded), (0, 2), "logs are never exported");

        let back = import(&client, &paths, &file, &|_, _, _| {}).await.unwrap();
        let g2 = paths.game_dir(&back.id);
        assert_eq!(std::fs::read(g2.join("config/settings.toml")).unwrap(), b"a = 1");
        assert!(g2.join("mods/my-own-mod.jar.disabled").exists());
        assert!(!g2.join("logs").exists());
        assert_eq!((back.name.as_str(), back.loader), ("My Pack", Loader::Fabric));
        std::fs::remove_dir_all(root).unwrap();
    }

    /// A real Modrinth mod becomes a link (not embedded) and comes back with its metadata.
    #[tokio::test]
    async fn round_trip_links_modrinth_files() {
        let root = std::env::temp_dir().join(format!("tessera-tapack-mr-{}", std::process::id()));
        let paths = Paths::new(root.clone());
        let client = crate::core::http_client();
        let inst = instances::create(&paths, "Linked", "1.21.1", Loader::Fabric, Some("0.16.9".into()), None).unwrap();
        modrinth::install(&client, &paths, &inst.id, "P7dR8mSH", "mod", None).await.unwrap(); // Fabric API
        // drop the tracking, so export has to find it by hash like a hand-added mod
        let mut bare = instances::get(&paths, &inst.id).unwrap();
        bare.mods.clear();
        instances::save(&paths, &bare).unwrap();

        let file = root.join("linked.tapack");
        let opts = ExportOptions { name: "Linked".into(), version: "1".into(), author: String::new(), summary: String::new(), include: vec!["mods".into()], format: PackFormat::Tapack };
        let report = export(&client, &paths, &inst.id, &file, opts, &|_, _, _| {}).await.unwrap();
        assert_eq!((report.linked, report.embedded), (1, 0));
        assert!(report.bytes < 4096, "a link, not the jar: {} bytes", report.bytes);

        let back = import(&client, &paths, &file, &|_, _, _| {}).await.unwrap();
        assert_eq!(back.mods.len(), 1);
        assert_eq!(back.mods[0].title, "Fabric API");
        assert!(paths.game_dir(&back.id).join("mods").join(&back.mods[0].filename).exists());
        std::fs::remove_dir_all(root).unwrap();
    }
}

#[cfg(test)]
mod mrpack_export {
    use super::*;

    /// Network: installs two mods from Modrinth, exports as .mrpack, imports it back.
    /// cargo test mrpack_round_trip -- --ignored --nocapture
    #[tokio::test]
    #[ignore]
    async fn mrpack_round_trip() {
        let root = std::env::temp_dir().join(format!("tessera-mrpack-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        let paths = Paths::new(root.clone());
        let client = crate::core::http_client();
        let inst = instances::create(&paths, "Round Trip", "1.21.1", Loader::Fabric, Some("0.16.9".into()), None).unwrap();
        for project in ["P7dR8mSH", "AANobbMI"] {
            // Fabric API, Sodium
            modrinth::install(&client, &paths, &inst.id, project, "mod", None).await.unwrap();
        }
        let game = paths.game_dir(&inst.id);
        std::fs::create_dir_all(game.join("config")).unwrap();
        std::fs::write(game.join("config/test.toml"), "answer = 42\n").unwrap();
        std::fs::write(game.join("options.txt"), "fov:0.5\n").unwrap();
        // turn Sodium off: it must come back disabled
        let sodium = std::fs::read_dir(game.join("mods")).unwrap().flatten().map(|e| e.file_name().to_string_lossy().into_owned()).find(|n| n.starts_with("sodium")).unwrap();
        instances::toggle_content(&paths, &inst.id, "mod", None, &sodium).unwrap();

        let include: Vec<String> = entries(&paths, &inst.id).unwrap().into_iter().filter(|e| e.suggested).map(|e| e.name).collect();
        println!("include: {include:?}");
        let target = root.join("out.mrpack");
        let opts = ExportOptions { name: "Round Trip".into(), version: "2.0.0".into(), author: String::new(), summary: "test".into(), include, format: PackFormat::Mrpack };
        let report = export(&client, &paths, &inst.id, &target, opts, &|_, _, _| {}).await.unwrap();
        println!("report: linked {} embedded {} bytes {}", report.linked, report.embedded, report.bytes);
        assert_eq!(report.linked, 1, "Fabric API linked; disabled Sodium goes in overrides");

        let mut zip = zip::ZipArchive::new(std::fs::File::open(&target).unwrap()).unwrap();
        let names: Vec<String> = (0..zip.len()).map(|i| zip.by_index(i).unwrap().name().to_string()).collect();
        println!("zip: {names:?}");
        assert!(names.contains(&"overrides/config/test.toml".to_string()));
        assert!(names.iter().any(|n| n.starts_with("overrides/mods/sodium") && n.ends_with(".disabled")));

        let back = crate::core::mrpack::import(&client, &paths, &target, crate::core::mrpack::Origin { project_id: None, version_id: None, icon_url: None }, &|_, _, _| {}).await.unwrap();
        let g2 = paths.game_dir(&back.id);
        let mods: Vec<String> = std::fs::read_dir(g2.join("mods")).unwrap().flatten().map(|e| e.file_name().to_string_lossy().into_owned()).collect();
        println!("imported: {} {} {:?} mods {mods:?}", back.name, back.game_version, back.loader_version);
        assert_eq!((back.game_version.as_str(), back.loader, back.loader_version.as_deref()), ("1.21.1", Loader::Fabric, Some("0.16.9")));
        assert!(mods.iter().any(|m| m.starts_with("fabric-api") && m.ends_with(".jar")));
        assert!(mods.iter().any(|m| m.starts_with("sodium") && m.ends_with(".disabled")));
        assert_eq!(std::fs::read_to_string(g2.join("config/test.toml")).unwrap(), "answer = 42\n");
        let _ = std::fs::remove_dir_all(&root);
    }
}

#[cfg(test)]
mod apply_update_test {
    use super::*;

    /// A shared copy gets the owner's newer pack: new mods in, removed mods out, worlds kept.
    #[tokio::test]
    async fn update_in_place_keeps_worlds() {
        let root = std::env::temp_dir().join(format!("tessera-apply-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        let paths = Paths::new(root.clone());
        let client = crate::core::http_client();
        let owner = instances::create(&paths, "Owner", "1.21.1", Loader::Fabric, Some("0.16.9".into()), None).unwrap();
        let og = paths.game_dir(&owner.id);
        std::fs::create_dir_all(og.join("mods")).unwrap();
        std::fs::create_dir_all(og.join("config")).unwrap();
        std::fs::write(og.join("mods/old-mod.jar"), b"old").unwrap();
        std::fs::write(og.join("config/a.toml"), b"v1").unwrap();
        let export_as = |file: &str| {
            let file = root.join(file);
            let opts = ExportOptions { name: "P".into(), version: "1".into(), author: String::new(), summary: String::new(), include: vec!["mods".into(), "config".into()], format: PackFormat::Tapack };
            (file, opts)
        };
        let (v1, o1) = export_as("v1.tapack");
        export(&client, &paths, &owner.id, &v1, o1, &|_, _, _| {}).await.unwrap();

        // the friend's copy, with a world they played
        let copy = import(&client, &paths, &v1, &|_, _, _| {}).await.unwrap();
        let cg = paths.game_dir(&copy.id);
        std::fs::create_dir_all(cg.join("saves/My World")).unwrap();
        std::fs::write(cg.join("saves/My World/level.dat"), b"world").unwrap();
        assert!(cg.join("mods/old-mod.jar").exists());

        // the owner swaps the mod and changes a config
        std::fs::remove_file(og.join("mods/old-mod.jar")).unwrap();
        std::fs::write(og.join("mods/new-mod.jar"), b"new").unwrap();
        std::fs::write(og.join("config/a.toml"), b"v2").unwrap();
        let (v2, o2) = export_as("v2.tapack");
        export(&client, &paths, &owner.id, &v2, o2, &|_, _, _| {}).await.unwrap();

        let before = instances::list(&paths).unwrap().len();
        let updated = apply_update(&client, &paths, &copy.id, &v2, &|_, _, _| {}).await.unwrap();
        assert_eq!(updated.id, copy.id);
        assert!(!cg.join("mods/old-mod.jar").exists(), "removed mods go");
        assert_eq!(std::fs::read(cg.join("mods/new-mod.jar")).unwrap(), b"new");
        assert_eq!(std::fs::read(cg.join("config/a.toml")).unwrap(), b"v2");
        assert_eq!(std::fs::read(cg.join("saves/My World/level.dat")).unwrap(), b"world", "worlds stay");
        assert_eq!(instances::list(&paths).unwrap().len(), before, "no leftover temporary instance");
        let _ = std::fs::remove_dir_all(&root);
    }
}
