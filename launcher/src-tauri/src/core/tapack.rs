pub const FORMAT: u32 = 1;
const MANIFEST: &str = "tessera.pack.json";

#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct Manifest {
    pub format: u32,
    pub name: String,
    pub version: String,
    #[serde(default)]
    pub author: String,
    #[serde(default)]
    pub summary: String,
    pub minecraft: String,
    pub loader: LoaderRef,
    #[serde(default)]
    pub icon: Option<Icon>,
    #[serde(default)]
    pub memory_mb: Option<u32>,
    #[serde(default)]
    pub content: Vec<ContentRef>,
}

#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct LoaderRef {
    #[serde(rename = "type")]
    pub kind: Loader,
    pub version: Option<String>,
}

#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct ContentRef {
    /// "mod" | "resourcepack" | "shader"
    pub kind: String,
    /// Relative to the game folder, without ".disabled".
    pub path: String,
    pub enabled: bool,
    pub url: String,
    pub sha1: String,
    pub size: u64,
    pub title: String,
    #[serde(default)]
    pub version: Option<String>,
    #[serde(default)]
    pub icon_url: Option<String>,
    #[serde(default)]
    pub source: Option<Source>,
    #[serde(default)]
    pub env: Option<Env>,
}

#[derive(Serialize, Deserialize, Clone, Debug)]
#[serde(tag = "type", rename_all = "lowercase")]
pub enum Source {
    Modrinth { project_id: String, version_id: String },
}

/// Modrinth's side support: "required" | "optional" | "unsupported" | "unknown".
#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct Env {
    pub client: String,
    pub server: String,
}

// ── export ─────────────────────────────────────────────────────────────

#[derive(Serialize, Clone, Debug)]
pub struct Entry {
    pub name: String,
    pub is_dir: bool,
    pub size: u64,
    /// Suggested for a pack (configs and content yes, worlds and logs no).
    pub suggested: bool,
}

/// Never exported: machine-specific or regenerated by the game.
const NEVER: &[&str] = &["logs", "crash-reports", "natives", ".fabric", ".quilt", "usercache.json", "usernamecache.json", "command_history.txt", ".DS_Store"];
const NOT_SUGGESTED: &[&str] = &["saves", "screenshots", "servers.dat", "servers.dat_old", "backups", "downloads", "journeymap", "xaero", "XaeroWaypoints", "XaeroWorldMap"];

fn dir_size(path: &Path) -> u64 {
    let Ok(meta) = std::fs::symlink_metadata(path) else { return 0 };
    if meta.is_file() {
        return meta.len();
    }
    std::fs::read_dir(path).map(|d| d.flatten().map(|e| dir_size(&e.path())).sum()).unwrap_or(0)
}

/// Top-level files and folders of the game folder, for the export dialog.
pub fn entries(paths: &Paths, id: &str) -> Result<Vec<Entry>> {
    instances::get(paths, id)?;
    let mut out = Vec::new();
    for e in std::fs::read_dir(paths.game_dir(id))?.flatten() {
        let name = e.file_name().to_string_lossy().into_owned();
        if NEVER.contains(&name.as_str()) {
            continue;
        }
        let path = e.path();
        out.push(Entry { suggested: !NOT_SUGGESTED.contains(&name.as_str()), is_dir: path.is_dir(), size: dir_size(&path), name });
    }
    out.sort_by(|a, b| b.is_dir.cmp(&a.is_dir).then(a.name.to_lowercase().cmp(&b.name.to_lowercase())));
    Ok(out)
}

#[derive(Deserialize, Debug)]
pub struct ExportOptions {
    pub name: String,
    pub version: String,
    #[serde(default)]
    pub author: String,
    #[serde(default)]
    pub summary: String,
    /// Top-level names from `entries` to include.
    pub include: Vec<String>,
    /// .tapack (default) or Modrinth's .mrpack.
    #[serde(default)]
    pub format: PackFormat,
}

#[derive(Deserialize, Clone, Copy, Debug, Default, PartialEq)]
#[serde(rename_all = "lowercase")]
pub enum PackFormat {
    #[default]
    Tapack,
    Mrpack,
}

#[derive(Serialize, Debug)]
pub struct ExportReport {
    pub linked: usize,
    pub embedded: usize,
    pub bytes: u64,
}

pub(crate) fn walk(base: &Path, rel: PathBuf, out: &mut Vec<PathBuf>) {
    let path = base.join(&rel);
    if path.is_dir() {
        if let Ok(d) = std::fs::read_dir(&path) {
            for e in d.flatten() {
                let name = e.file_name();
                if NEVER.contains(&name.to_string_lossy().as_ref()) {
                    continue;
                }
                walk(base, rel.join(name), out);
            }
        }
    } else if path.is_file() {
        out.push(rel);
    }
}

pub(crate) fn sha1_file(path: &Path) -> Result<String> {
    let mut f = std::fs::File::open(path)?;
    let mut hasher = Sha1::new();
    let mut buf = vec![0u8; 64 * 1024];
    loop {
        let n = f.read(&mut buf)?;
        if n == 0 {
            break;
        }
        hasher.update(&buf[..n]);
    }
    Ok(hex::encode(hasher.finalize()))
}

/// `mods/x.jar` → mod, `resourcepacks/x.zip` → resourcepack, `shaderpacks/x.zip` → shader (direct children only).
fn content_kind(rel: &Path) -> Option<&'static str> {
    let mut parts = rel.components();
    let top = parts.next()?.as_os_str().to_str()?;
    parts.next()?;
    if parts.next().is_some() {
        return None;
    }
    match top {
        "mods" => Some("mod"),
        "resourcepacks" => Some("resourcepack"),
        "shaderpacks" => Some("shader"),
        _ => None,
    }
}

pub(crate) fn rel_string(rel: &Path) -> String {
    rel.to_string_lossy().replace('\\', "/")
}

pub async fn export(
    client: &reqwest::Client,
    paths: &Paths,
    id: &str,
    target: &Path,
    opts: ExportOptions,
    progress: &(dyn Fn(&str, usize, usize) + Send + Sync),
) -> Result<ExportReport> {
    let inst = instances::get(paths, id)?;
    let game = paths.game_dir(id);
    let include: HashSet<&str> = opts.include.iter().map(String::as_str).collect();
    if opts.name.trim().is_empty() {
        bail!("Give the pack a name");
    }

    progress("Collecting files", 0, 0);
    let mut files = Vec::new();
    for e in std::fs::read_dir(&game)?.flatten() {
        let name = e.file_name().to_string_lossy().into_owned();
        if include.contains(name.as_str()) && !NEVER.contains(&name.as_str()) {
            walk(&game, PathBuf::from(&name), &mut files);
        }
    }

    // Hash content files and ask Modrinth which of them it knows.
    let mut hashes: HashMap<PathBuf, String> = HashMap::new();
    let candidates: Vec<&PathBuf> = files.iter().filter(|f| content_kind(f).is_some()).collect();
    for (i, rel) in candidates.iter().enumerate() {
        progress("Checking files", i, candidates.len());
        hashes.insert((*rel).clone(), sha1_file(&game.join(rel))?);
    }
    progress("Looking up Modrinth", 0, 0);
    let known = modrinth::versions_by_sha1(client, hashes.values().cloned().collect()).await.unwrap_or_default();
    let project_ids: Vec<String> = known.values().map(|v| v.project_id.clone()).collect::<HashSet<_>>().into_iter().collect();
    let projects = modrinth::projects(client, &project_ids).await.unwrap_or_default();

    let mut content = Vec::new();
    let mut embed = Vec::new();
    for rel in &files {
        let linked = hashes.get(rel).and_then(|h| known.get(h).map(|v| (h, v)));
        let Some((hash, version)) = linked else {
            embed.push(rel.clone());
            continue;
        };
        let Some(file) = version.file_with_sha1(hash) else {
            embed.push(rel.clone());
            continue;
        };
        let rel_s = rel_string(rel);
        let enabled = !rel_s.ends_with(".disabled");
        let project = projects.get(&version.project_id);
        content.push(ContentRef {
            kind: content_kind(rel).unwrap_or("mod").into(),
            path: rel_s.trim_end_matches(".disabled").to_string(),
            enabled,
            url: file.url.clone(),
            sha1: hash.clone(),
            size: file.size,
            title: project.map(|p| p.title.clone()).unwrap_or_else(|| file.filename.clone()),
            version: Some(version.version_number.clone()),
            icon_url: project.and_then(|p| p.icon_url.clone()),
            source: Some(Source::Modrinth { project_id: version.project_id.clone(), version_id: version.id.clone() }),
            env: project.map(|p| Env { client: p.client_side.clone(), server: p.server_side.clone() }),
        });
    }
    content.sort_by(|a, b| a.path.cmp(&b.path));

    let manifest = Manifest {
        format: FORMAT,
        name: opts.name.trim().into(),
        version: if opts.version.trim().is_empty() { "1.0.0".into() } else { opts.version.trim().into() },
        author: opts.author.trim().into(),
        summary: opts.summary.trim().into(),
        minecraft: inst.game_version.clone(),
        loader: LoaderRef { kind: inst.loader, version: inst.loader_version.clone() },
        icon: inst.icon.clone(),
        memory_mb: inst.memory_mb,
        content,
    };

    if opts.format == PackFormat::Mrpack {
        return write_mrpack(&inst, &game, target, &manifest, embed, progress);
    }

    // Write to a temp file next to the target, then move it into place.
    let tmp = target.with_extension("tapack.part");
    let result = (|| -> Result<u64> {
        let mut zip = zip::ZipWriter::new(std::fs::File::create(&tmp).context("creating the pack file")?);
        let deflated = zip::write::SimpleFileOptions::default().compression_method(zip::CompressionMethod::Deflated);
        let stored = zip::write::SimpleFileOptions::default().compression_method(zip::CompressionMethod::Stored);
        zip.start_file(MANIFEST, deflated)?;
        zip.write_all(&serde_json::to_vec_pretty(&manifest)?)?;
        if matches!(inst.icon, Some(Icon::File)) {
            if let Ok(bytes) = std::fs::read(paths.instance(id).join("icon.png")) {
                zip.start_file("icon.png", stored)?;
                zip.write_all(&bytes)?;
            }
        }
        for (i, rel) in embed.iter().enumerate() {
            progress("Packing files", i, embed.len());
            let name = rel_string(rel);
            // jars and zips are compressed already
            let opts = if name.ends_with(".jar") || name.ends_with(".zip") { stored } else { deflated };
            zip.start_file(format!("overrides/{name}"), opts)?;
            let mut f = std::fs::File::open(game.join(rel))?;
            std::io::copy(&mut f, &mut zip)?;
        }
        zip.finish()?;
        Ok(std::fs::metadata(&tmp)?.len())
    })();
    match result {
        Ok(bytes) => {
            std::fs::rename(&tmp, target)?;
            Ok(ExportReport { linked: manifest.content.len(), embedded: embed.len(), bytes })
        }
        Err(e) => {
            let _ = std::fs::remove_file(&tmp);
            Err(e)
        }
    }
}

/// The same pack as a Modrinth .mrpack (modrinth.index.json + overrides/), for the Modrinth
/// App, Prism, and anything else that reads them. .mrpack has no "disabled" flag, so
/// disabled Modrinth files go into overrides as they are; there's no place for the icon.
fn write_mrpack(
    inst: &Instance,
    game: &Path,
    target: &Path,
    manifest: &Manifest,
    mut embed: Vec<PathBuf>,
    progress: &(dyn Fn(&str, usize, usize) + Send + Sync),
) -> Result<ExportReport> {
    let side = |s: Option<&str>| match s {
        Some("unsupported") => "unsupported",
        Some("optional") => "optional",
        _ => "required",
    };
    let mut files = Vec::new();
    let enabled: Vec<&ContentRef> = manifest.content.iter().filter(|c| c.enabled).collect();
    for c in &manifest.content {
        if !c.enabled {
            embed.push(PathBuf::from(format!("{}.disabled", c.path)));
        }
    }
    for (i, c) in enabled.iter().enumerate() {
        progress("Hashing files", i, enabled.len());
        files.push(json!({
            "path": c.path,
            "hashes": { "sha1": c.sha1, "sha512": super::serverpack::sha512_file(&game.join(&c.path))? },
            "env": { "client": side(c.env.as_ref().map(|e| e.client.as_str())), "server": side(c.env.as_ref().map(|e| e.server.as_str())) },
            "downloads": [c.url],
            "fileSize": c.size,
        }));
    }
    let mut deps = serde_json::Map::new();
    deps.insert("minecraft".into(), json!(inst.game_version));
    let loader_key = match inst.loader {
        Loader::Vanilla => None,
        Loader::Fabric => Some("fabric-loader"),
        Loader::Quilt => Some("quilt-loader"),
        Loader::Forge => Some("forge"),
        Loader::NeoForge => Some("neoforge"),
    };
    if let (Some(k), Some(v)) = (loader_key, &inst.loader_version) {
        deps.insert(k.into(), json!(v));
    }
    let mut index = json!({
        "formatVersion": 1,
        "game": "minecraft",
        "versionId": manifest.version,
        "name": manifest.name,
        "files": files,
        "dependencies": deps,
    });
    if !manifest.summary.is_empty() {
        index["summary"] = json!(manifest.summary);
    }

    let tmp = target.with_extension("mrpack.part");
    let result = (|| -> Result<u64> {
        let mut zip = zip::ZipWriter::new(std::fs::File::create(&tmp).context("creating the pack file")?);
        let deflated = zip::write::SimpleFileOptions::default().compression_method(zip::CompressionMethod::Deflated);
        let stored = zip::write::SimpleFileOptions::default().compression_method(zip::CompressionMethod::Stored);
        zip.start_file("modrinth.index.json", deflated)?;
        zip.write_all(serde_json::to_string_pretty(&index)?.as_bytes())?;
        for (i, rel) in embed.iter().enumerate() {
            progress("Packing files", i, embed.len());
            let name = rel_string(rel);
            let opts = if name.ends_with(".jar") || name.ends_with(".zip") || name.ends_with(".disabled") { stored } else { deflated };
            zip.start_file(format!("overrides/{name}"), opts)?;
            std::io::copy(&mut std::fs::File::open(game.join(rel))?, &mut zip)?;
        }
        zip.finish()?;
        Ok(std::fs::metadata(&tmp)?.len())
    })();
    match result {
        Ok(bytes) => {
            std::fs::rename(&tmp, target)?;
            Ok(ExportReport { linked: files.len(), embedded: embed.len(), bytes })
        }
        Err(e) => {
            let _ = std::fs::remove_file(&tmp);
            Err(e)
        }
    }
}

