//! Tessera packs (.tapack): a zip with
//!
//! ```text
//! tessera.pack.json   manifest: name, version, Minecraft + loader, icon, content list
//! overrides/…         files copied into the game folder as they are (configs, options, files
//!                     Modrinth doesn't know)
//! icon.png            when the icon is an uploaded image
//! ```
//!
//! Content Modrinth knows (found by file hash at export, also for mods added by hand) is a
//! download link with its SHA-1, so packs stay small; `env` says whether the client and/or
//! the server needs it, which is what server sync uses later.

use std::collections::{HashMap, HashSet};
use std::io::{Read, Write};
use std::path::{Path, PathBuf};

use anyhow::{anyhow, bail, Context, Result};
use serde::{Deserialize, Serialize};
use serde_json::json;
use sha1::{Digest, Sha1};

use super::download::{download_all, Download};
use super::instances::{self, Icon, InstalledMod, Instance, Loader, PackSource};
use super::modrinth;
